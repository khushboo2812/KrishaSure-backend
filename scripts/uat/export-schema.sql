-- Run this in the PRODUCTION Supabase SQL editor. It only READS: it
-- builds the text of the SQL needed to recreate the (empty) tables in
-- another database. It copies no data.
--
-- The result is one cell. Copy it, paste it into the UAT project's
-- SQL editor, and run it there.
--
-- Covers tables, sequences, defaults, primary and unique keys, foreign
-- keys, checks and indexes in the "public" schema.
SELECT string_agg(stmt, E'\n' ORDER BY ord, name) AS schema_sql
FROM (
  -- 1. sequences (serial / bigserial columns need them before the tables)
  SELECT 1 AS ord, s.sequencename::text AS name,
         format('CREATE SEQUENCE IF NOT EXISTS public.%I AS %s;', s.sequencename, s.data_type) AS stmt
  FROM pg_sequences s
  WHERE s.schemaname = 'public'
    -- identity columns create and manage their own sequence
    AND NOT EXISTS (
      SELECT 1 FROM pg_depend d JOIN pg_class sc ON sc.oid = d.objid
      WHERE d.deptype = 'i' AND sc.relkind = 'S' AND sc.relname = s.sequencename)

  UNION ALL
  -- 2. tables with columns, types, defaults, NOT NULL and identity
  SELECT 2, c.relname::text,
         format('CREATE TABLE IF NOT EXISTS public.%I (%s);', c.relname,
           string_agg(
             format('%I %s%s%s%s', a.attname, format_type(a.atttypid, a.atttypmod),
               CASE a.attidentity WHEN 'a' THEN ' GENERATED ALWAYS AS IDENTITY' WHEN 'd' THEN ' GENERATED BY DEFAULT AS IDENTITY' ELSE '' END,
               CASE WHEN a.attgenerated = '' AND d.adbin IS NOT NULL THEN ' DEFAULT ' || pg_get_expr(d.adbin, d.adrelid) ELSE '' END,
               CASE WHEN a.attnotnull THEN ' NOT NULL' ELSE '' END),
             ', ' ORDER BY a.attnum))
  FROM pg_class c
  JOIN pg_namespace n ON n.oid = c.relnamespace
  JOIN pg_attribute a ON a.attrelid = c.oid AND a.attnum > 0 AND NOT a.attisdropped
  LEFT JOIN pg_attrdef d ON d.adrelid = c.oid AND d.adnum = a.attnum
  WHERE n.nspname = 'public' AND c.relkind = 'r'
  GROUP BY c.relname

  UNION ALL
  -- 3. primary keys, unique and check constraints
  SELECT 3, c.relname || '.' || con.conname,
         format('ALTER TABLE public.%I ADD CONSTRAINT %I %s;', c.relname, con.conname, pg_get_constraintdef(con.oid))
  FROM pg_constraint con
  JOIN pg_class c ON c.oid = con.conrelid
  JOIN pg_namespace n ON n.oid = c.relnamespace
  WHERE n.nspname = 'public' AND con.contype IN ('p', 'u', 'c')

  UNION ALL
  -- 4. indexes that are not already created by a constraint above
  SELECT 4, i.indexname::text, i.indexdef || ';'
  FROM pg_indexes i
  WHERE i.schemaname = 'public'
    AND i.indexname NOT IN (SELECT conname FROM pg_constraint)

  UNION ALL
  -- 5. foreign keys last, once every table exists
  SELECT 5, c.relname || '.' || con.conname,
         format('ALTER TABLE public.%I ADD CONSTRAINT %I %s;', c.relname, con.conname, pg_get_constraintdef(con.oid))
  FROM pg_constraint con
  JOIN pg_class c ON c.oid = con.conrelid
  JOIN pg_namespace n ON n.oid = c.relnamespace
  WHERE n.nspname = 'public' AND con.contype = 'f'

  UNION ALL
  -- 6. tie each serial sequence to its column, so dropping the column drops it
  SELECT 6, c.relname || '.' || a.attname,
         format('ALTER SEQUENCE public.%I OWNED BY public.%I.%I;', substring(pg_get_expr(d.adbin, d.adrelid) FROM $q$nextval\('(?:public\.)?"?([^'"]+)"?'::regclass\)$q$), c.relname, a.attname)
  FROM pg_class c
  JOIN pg_namespace n ON n.oid = c.relnamespace
  JOIN pg_attribute a ON a.attrelid = c.oid AND a.attnum > 0 AND NOT a.attisdropped
  JOIN pg_attrdef d ON d.adrelid = c.oid AND d.adnum = a.attnum
  WHERE n.nspname = 'public' AND c.relkind = 'r' AND pg_get_expr(d.adbin, d.adrelid) LIKE 'nextval(%'
) t;
